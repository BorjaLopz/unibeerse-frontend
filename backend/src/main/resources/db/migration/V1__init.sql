CREATE TABLE beers (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    brand      VARCHAR(120) NOT NULL DEFAULT '',
    name       VARCHAR(200) NOT NULL,
    style      VARCHAR(100) NOT NULL DEFAULT '',
    abv        NUMERIC(4,1),
    country    VARCHAR(200) NOT NULL DEFAULT '',
    score      NUMERIC(3,1),
    notes      VARCHAR(1000) NOT NULL DEFAULT '',
    image      VARCHAR(300),
    thumb      VARCHAR(300),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE comments (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    beer_id     BIGINT NOT NULL REFERENCES beers (id) ON DELETE CASCADE,
    uid         VARCHAR(128),            -- NULL en los comentarios importados de la version antigua
    author_name VARCHAR(100) NOT NULL,
    text        VARCHAR(1000) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_comments_beer ON comments (beer_id, created_at);

CREATE TABLE messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       VARCHAR(10) NOT NULL CHECK (kind IN ('contact', 'issue')),
    beer_id    BIGINT REFERENCES beers (id) ON DELETE SET NULL,
    name       VARCHAR(100) NOT NULL,
    email      VARCHAR(200) NOT NULL,
    text       VARCHAR(2000) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
